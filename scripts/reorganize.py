moved = []
failed = []

for src_rel, dst_rel in MAPPING:
    src = BASE / src_rel
    dst = BASE / dst_rel

    if not src.exists():
        print(f"  MISS: {src_rel}")
        failed.append(src_rel)
        continue

    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(src), str(dst))
    print(f"  OK  {src_rel.split('/')[-1]}")
    print(f"   -> {dst_rel}")
    moved.append((src_rel, dst_rel))

print(f"\n이동: {len(moved)}건 / 실패: {len(failed)}건")
if failed:
    print("실패 목록:")
    for f in failed:
        print(f"  {f}")

