def main():
    spec = json.loads(SPEC_PATH.read_text(encoding='utf-8'))

    for form_id, cell_guidance in GUIDANCE.items():
        form = spec[form_id]
        matched, missing = 0, []
        for field in form['fields']:
            cell = field['cell']
            if cell in cell_guidance:
                fillable, guidance = cell_guidance[cell]
                field['ai_fillable'] = fillable
                field['ai_guidance'] = guidance
                matched += 1
            else:
                field['ai_fillable'] = True  # 판단 안 된 필드는 안전하게 입력 가능으로 유지
                field['ai_guidance'] = field.get('guidance', '')
                missing.append(cell)

        print(f"{form['form_name']}: {matched}/{len(form['fields'])}개 AI 해설 반영"
              + (f" (미매칭: {missing})" if missing else ""))

    SPEC_PATH.write_text(json.dumps(spec, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f"\n💾 저장: {SPEC_PATH}")


if __name__ == '__main__':
    main()
